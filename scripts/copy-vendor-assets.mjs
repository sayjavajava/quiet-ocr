#!/usr/bin/env node
/**
 * Copies the OCR engine (tesseract.js's worker + tesseract.js-core's WASM
 * build + the English trained-data) from installed npm packages into
 * public/vendor/, where the page serves them from its own origin.
 *
 * Why copy rather than point at tesseract.js's default CDN
 * (cdn.jsdelivr.net): self-hosting means one fewer third party in the
 * trust chain, a pinned exact version instead of "whatever the CDN
 * currently serves", and no dependency on that CDN's uptime. It does NOT
 * make this app offline-capable — the page still needs the network on
 * first load to fetch these files from wherever this site is hosted.
 * That's the deliberate, documented difference from this project's
 * sibling, OffGridPDF: this tool fetches its own code, it just never
 * transmits your files. See README.md.
 *
 * Output is gitignored and regenerated by `npm run build` (also wired
 * into CI before the Pages deploy) — never commit these binaries.
 */
import { copyFileSync, mkdirSync, existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT_DIR = join(ROOT, "public", "vendor");

// LSTM-only engine (OEM 1) — smaller than the combined legacy+LSTM build
// and the only mode this app uses. See F-18 in the offline-pdf-utility
// repo's private audit for how this variant was chosen.
const FILES = [
  ["tesseract.js/dist/worker.min.js", "worker.min.js"],
  ["tesseract.js/dist/tesseract.min.js", "tesseract.min.js"],
  ["tesseract.js-core/tesseract-core-lstm.wasm.js", "tesseract-core-lstm.wasm.js"],
  ["@tesseract.js-data/eng/4.0.0_best_int/eng.traineddata.gz", "eng.traineddata.gz"],
  // Multi-language OCR: each language's trained data is only ever fetched
  // by the browser when that language is actually selected (tesseract.js
  // requests exactly `${langPath}/${lang}.traineddata.gz` for whichever
  // language(s) it's given — confirmed directly from
  // node_modules/tesseract.js/src/worker-script/index.js), so vendoring
  // this whole list costs nothing extra for anyone who only ever uses
  // English. Same 4.0.0_best_int (LSTM-only) variant as eng above, for
  // every language — confirmed each package actually ships it before
  // relying on that, not assumed from eng alone. Chosen for real-world
  // coverage (the world's most-spoken languages) and because every one of
  // these was directly verified (real recognize() calls against real
  // rendered sentences, before this list was finalized) to both render
  // correctly and recognize accurately in this project's own environment
  // — see test/fixtures/manifest.json's per-language fixtures.
  ["@tesseract.js-data/fra/4.0.0_best_int/fra.traineddata.gz", "fra.traineddata.gz"],
  ["@tesseract.js-data/spa/4.0.0_best_int/spa.traineddata.gz", "spa.traineddata.gz"],
  ["@tesseract.js-data/deu/4.0.0_best_int/deu.traineddata.gz", "deu.traineddata.gz"],
  ["@tesseract.js-data/por/4.0.0_best_int/por.traineddata.gz", "por.traineddata.gz"],
  ["@tesseract.js-data/ita/4.0.0_best_int/ita.traineddata.gz", "ita.traineddata.gz"],
  ["@tesseract.js-data/rus/4.0.0_best_int/rus.traineddata.gz", "rus.traineddata.gz"],
  ["@tesseract.js-data/ara/4.0.0_best_int/ara.traineddata.gz", "ara.traineddata.gz"],
  ["@tesseract.js-data/hin/4.0.0_best_int/hin.traineddata.gz", "hin.traineddata.gz"],
  ["@tesseract.js-data/chi_sim/4.0.0_best_int/chi_sim.traineddata.gz", "chi_sim.traineddata.gz"],
  ["@tesseract.js-data/jpn/4.0.0_best_int/jpn.traineddata.gz", "jpn.traineddata.gz"],
  ["@tesseract.js-data/kor/4.0.0_best_int/kor.traineddata.gz", "kor.traineddata.gz"],
  // PDF input (F-3): rasterizes each page to an image before handing it to
  // the same OCR pipeline images already use. Non-legacy build — this page
  // is only ever served over http(s), not file://, so none of the
  // worker-construction workarounds the offline-pdf-utility sibling needs
  // apply here; a plain self-hosted workerSrc URL is enough.
  ["pdfjs-dist/build/pdf.min.mjs", "pdf.min.mjs"],
  ["pdfjs-dist/build/pdf.worker.min.mjs", "pdf.worker.min.mjs"],
  // Word-document export: recognized text is handed to the user as a real
  // .docx (or a .zip of several), not a plain-text download — see
  // public/docx-export.js. `docx`'s dist/index.mjs is already a single,
  // dependency-free bundled ES module (its own jszip/nanoid/xml-js
  // dependencies are bundled in) — the same "self-hosted, no bundler
  // needed" shape as pdf.js above, confirmed by inspecting the file before
  // vendoring it, not assumed from the package's README alone.
  ["docx/dist/index.mjs", "docx.mjs"],
  // Only used to zip multiple generated .docx files together when more
  // than one image/PDF was selected — fflate's browser build is also a
  // single dependency-free ES module.
  ["fflate/esm/browser.js", "fflate.mjs"],
  // Searchable-PDF export: recognized text can also be handed back as the
  // original page image with an invisible OCR text layer underneath (a
  // "sandwich PDF"), not just a .docx — see public/pdf-export.js. `dist/
  // pdf-lib.esm.min.js` is pdf-lib's real prebuilt browser bundle (zero
  // `import` statements, pako/@pdf-lib/upng/@pdf-lib/standard-fonts already
  // inlined), confirmed directly before vendoring it — NOT `es/index.js`,
  // which despite being pdf-lib's package.json "module" entry is actually
  // bare `export * from "./api/index"` re-exports across many
  // relative-import source files, not a bundle, and would break once
  // copied out of node_modules. pdf-lib stays a devDependency in
  // package.json (like every other browser-facing library here) — nothing
  // in this project runs on a Node server at request time.
  ["pdf-lib/dist/pdf-lib.esm.min.js", "pdf-lib.mjs"],
];

mkdirSync(OUT_DIR, { recursive: true });

for (const [src, destName] of FILES) {
  const srcPath = join(ROOT, "node_modules", src);
  if (!existsSync(srcPath)) {
    console.error(`✗ Missing ${srcPath} — run \`npm install\` first.`);
    process.exit(1);
  }
  copyFileSync(srcPath, join(OUT_DIR, destName));
  console.log(`  copied ${src} -> public/vendor/${destName}`);
}

// UI type: Space Grotesk (display) + Inter (body), self-hosted for the same
// reason as everything else here — one fewer third party, a pinned version,
// no dependency on a font CDN's uptime. Only the latin + latin-ext subsets
// are copied — this is the site's own chrome font (buttons, labels, the
// page's own English/Latin-script copy), not what renders recognized text:
// the result <textarea> (style.css, textarea#result) uses --font-mono,
// which is `ui-monospace, 'SF Mono', 'Cascadia Mono', monospace` — generic/
// system font keywords, no @font-face of this project's own — so it already
// relies on the browser/OS's own font substitution for glyphs those don't
// cover, the same fallback mechanism confirmed (real screenshot, not
// assumed) to render Cyrillic/Arabic/Devanagari/CJK correctly during this
// feature's own research. Each @fontsource-variable package ships a dozen+
// additional script subsets (cyrillic, greek, vietnamese, …) this app's own
// UI chrome has no use for.
const FONT_DIR = join(OUT_DIR, "fonts");
mkdirSync(FONT_DIR, { recursive: true });

const FONT_FILES = [
  ["@fontsource-variable/inter/files/inter-latin-wght-normal.woff2", "inter-latin-wght-normal.woff2"],
  ["@fontsource-variable/inter/files/inter-latin-ext-wght-normal.woff2", "inter-latin-ext-wght-normal.woff2"],
  ["@fontsource-variable/space-grotesk/files/space-grotesk-latin-wght-normal.woff2", "space-grotesk-latin-wght-normal.woff2"],
  ["@fontsource-variable/space-grotesk/files/space-grotesk-latin-ext-wght-normal.woff2", "space-grotesk-latin-ext-wght-normal.woff2"],
];

for (const [src, destName] of FONT_FILES) {
  const srcPath = join(ROOT, "node_modules", src);
  if (!existsSync(srcPath)) {
    console.error(`✗ Missing ${srcPath} — run \`npm install\` first.`);
    process.exit(1);
  }
  copyFileSync(srcPath, join(FONT_DIR, destName));
  console.log(`  copied ${src} -> public/vendor/fonts/${destName}`);
}

