#!/usr/bin/env node
/**
 * Copies the OCR engine (tesseract.js's worker + tesseract.js-core's WASM
 * build + the English trained-data) from installed npm packages into
 * public/vendor/, where the page serves them from its own origin.
 *
 * Why copy rather than point at tesseract.js's default CDN
 * (cdn.jsdelivr.net): self-hosting means one fewer third party in the
 * trust chain, a pinned exact version instead of "whatever the CDN
 * currently serves", and no dependency on that CDN's uptime. It does NOT
 * make this app offline-capable — the page still needs the network on
 * first load to fetch these files from wherever this site is hosted.
 * That's the deliberate, documented difference from this project's
 * sibling, OffGridPDF: this tool fetches its own code, it just never
 * transmits your files. See README.md.
 *
 * Output is gitignored and regenerated by `npm run build` (also wired
 * into CI before the Pages deploy) — never commit these binaries.
 */
import { copyFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT_DIR = join(ROOT, "public", "vendor");

// LSTM-only engine (OEM 1) — smaller than the combined legacy+LSTM build
// and the only mode this app uses. See F-18 in the offline-pdf-utility
// repo's private audit for how this variant was chosen.
const FILES = [
  ["tesseract.js/dist/worker.min.js", "worker.min.js"],
  ["tesseract.js/dist/tesseract.min.js", "tesseract.min.js"],
  ["tesseract.js-core/tesseract-core-lstm.wasm.js", "tesseract-core-lstm.wasm.js"],
  ["@tesseract.js-data/eng/4.0.0_best_int/eng.traineddata.gz", "eng.traineddata.gz"],
  // PDF input (F-3): rasterizes each page to an image before handing it to
  // the same OCR pipeline images already use. Non-legacy build — this page
  // is only ever served over http(s), not file://, so none of the
  // worker-construction workarounds the offline-pdf-utility sibling needs
  // apply here; a plain self-hosted workerSrc URL is enough.
  ["pdfjs-dist/build/pdf.min.mjs", "pdf.min.mjs"],
  ["pdfjs-dist/build/pdf.worker.min.mjs", "pdf.worker.min.mjs"],
];

mkdirSync(OUT_DIR, { recursive: true });

for (const [src, destName] of FILES) {
  const srcPath = join(ROOT, "node_modules", src);
  if (!existsSync(srcPath)) {
    console.error(`✗ Missing ${srcPath} — run \`npm install\` first.`);
    process.exit(1);
  }
  copyFileSync(srcPath, join(OUT_DIR, destName));
  console.log(`  copied ${src} -> public/vendor/${destName}`);
}

console.log(`✓ Vendor assets ready in public/vendor/`);
